export function celsiusParaFahrenheit(celsius) {
    return (celsius * 9 / 5) + 32;
}

export function horasParaMinutos(horas) {
    return horas * 60;
}

export function idadeEmDias(idade) {
    return idade * 365;
}

export function kmParaMetros(km) {
    return km * 1000;
}

export function consumoMedio(km, litros) {
    return km / litros;
}
